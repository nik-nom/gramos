import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {getDemo} from '../src/demo.js';
import {renderContactPage} from '../src/contact.js';
import {renderNewsDetail} from '../src/news.js';
import {homeFooter,homeHeader} from '../src/homepage.js';

const {village,items}=getDemo();
globalThis.location={origin:'http://localhost:8000',pathname:'/demo/contact',search:''};
globalThis.window={GRAMOS_CONFIG:{turnstileSiteKey:''}};
globalThis.document={title:''};
const {renderPublic}=await import('../src/public.js');
const full=renderContactPage(village,'mr');
assert(full.includes('sv-contact-info-grid')&&full.includes('कार्यालयीन पत्ता')&&full.includes('ग्रामपंचायत स्थान'));
assert.equal((full.match(/role="tab"/g)||[]).length,4);
assert(full.includes('सूचना / तक्रार फॉर्म')&&full.includes('sv-contact-unavailable'));
assert(!full.includes('GramPanchayat Location')&&full.includes('समाजमाध्यमे'));
assert(!full.includes('src="javascript:'));
location.search='?contactTab=form';
assert(renderContactPage(village,'mr').includes('class="sv-contact-tab active" aria-selected="true"'));
const live={...village,id:'11111111-1111-4111-8111-111111111111',slug:'new-village',site_settings:{...village.site_settings,contact_map_embed_url:'javascript:alert(1)',facebook_url:'javascript:alert(1)'}};
window.GRAMOS_CONFIG.turnstileSiteKey='sitekey-test';
assert(renderContactPage(live,'mr').includes('id="visitorForm"'));
assert(!renderContactPage(live,'mr').includes('src="javascript:')); // Address-based Maps embed is allowed without a pasted embed URL.
assert(!renderContactPage(live,'mr').includes('href="javascript:'));
const news=items.filter(i=>i.kind==='news');
const story=news.find(i=>i.slug==='clean-village-drive');
const enhanced={...story,external_url:'https://example.org/source.pdf',details:{...story.details,source_title_mr:'मूळ बातमी',related_links_mr:'अधिक माहिती | https://example.org/related\nफसवणूक | javascript:alert(1)'}};
const detail=renderNewsDetail(village,[enhanced,...news.filter(x=>x!==story)],'mr','clean-village-drive');
assert(detail.includes('sv-news-related')&&detail.includes('मूळ बातमी')&&detail.includes('https://example.org/related'));
assert(detail.includes('news/')&&detail.includes('सर्व बातम्या पहा'));
assert(!detail.includes('href="javascript:'));
const footer=homeFooter({...village,phone:'0123456789',email:'demo@example.org'},'mr');
assert(footer.includes('>समाजमाध्यमे<')&&!footer.includes('>Social Media<'));
assert(footer.includes('/demo/contact')&&footer.includes('/demo/news'));
assert(footer.includes('https://rdd.maharashtra.gov.in/'));
assert(footer.includes('mailto:')&&footer.includes('tel:'));
assert(homeHeader(village,'mr','en').includes('>Home</a>'));
assert(homeHeader(village,'mr','en').includes('ग्रामपंचायत')&&homeHeader(village,'mr','en').includes('मराठी'));
location.search='';
const publicEn=await renderPublic(['demo','contact'],'en',{admin:false,ids:[]});
assert(publicEn.includes('sv-contact-page')&&publicEn.includes('>Home</a>'));
assert(publicEn.includes('कार्यालयीन पत्ता')&&!publicEn.includes('GramPanchayat Location'));
const admin=await readFile(new URL('../src/admin.js',import.meta.url),'utf8');
assert(admin.includes('id="contactSettingsForm"')&&admin.includes("payload.kind==='news'?['event_date'"));
assert(admin.includes('related_links_mr')&&admin.includes('contact_map_embed_url'));
const api=await readFile(new URL('../api/submit.js',import.meta.url),'utf8');
assert(api.includes('subject,attachment_path:path')&&api.includes("['general','complaint','suggestion','request']"));
const migration=await readFile(new URL('../database/09_contact_subject_v31.sql',import.meta.url),'utf8');
assert(migration.includes('add column if not exists subject'));
console.log('PASS v3.1: Marathi body/English nav, contact tabs, safe maps, full news links, clickable footer, scoped subject storage.');
