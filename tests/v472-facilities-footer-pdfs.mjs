import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {renderAboutPage} from '../src/about.js';
import {renderServicesPage} from '../src/services.js';
import {homeFooter} from '../src/homepage.js';
import {platformLegalNotice} from '../src/branding.js';
import {referenceForms,referenceFormsPaths} from '../src/services-reference.js';

globalThis.location={origin:'https://gramos-public.vercel.app',pathname:'/v/village-a/about',search:'',href:'https://gramos-public.vercel.app/v/village-a/about'};
const a={id:'village-a',slug:'village-a',name_mr:'गाव अ',name_en:'Village A',site_settings:{},phone:'9000000001',address_mr:'गाव अ चा पत्ता'};
const b={id:'village-b',slug:'village-b',name_mr:'गाव ब',name_en:'Village B',site_settings:{},phone:'9000000002',address_mr:'गाव ब चा पत्ता'};
const headings=['ग्रामपंचायतीची लोकसंख्या','एकूण कुटुंब संख्या','जॉबकार्ड धारक कुटुंब संख्या','बसविण्यात आलेले CCTV'];
const empty=renderAboutPage(a,[],'mr');
for(const heading of headings) assert(empty.includes(heading),'Missing fixed reference heading: '+heading);
assert((empty.match(/class="sv-a-no-data"/g)||[]).length===8,'four default no-data cards in both tabs');
assert(!empty.includes('5640'),'Do not copy population from another village');
const pub=[{kind:'about_facilities',status:'published',slug:'population',title_mr:'ग्रामपंचायतीची लोकसंख्या',details:{value:'5640'}}];
const renderedA=renderAboutPage(a,pub,'mr');
const renderedB=renderAboutPage(b,[],'mr');
assert(renderedA.includes('5640'));
assert(!renderedB.includes('5640'));
const job=[{kind:'about_facilities',status:'published',slug:'job-card-households',title_mr:'जॉबकार्ड धारक कुटुंब संख्या',details:{value:'8'}}];
const renderedJob=renderAboutPage(a,job,'mr');
assert((renderedJob.match(/<strong class="">8<\/strong>/g)||[]).length===2,'published job card count in two tabs');
assert((renderedJob.match(/class="sv-a-no-data"/g)||[]).length===6,'do not accidentally use job-card count as total households');
assert(homeFooter(a,'mr').includes('9000000001'));
assert(!homeFooter(a,'mr').includes('9000000002'));
assert(homeFooter(a,'mr').includes(platformLegalNotice()),'Original hardcoded legal notice unchanged');
assert(homeFooter(a,'mr').includes('समाजमाध्यमे'),'Marathi text unchanged');
assert.equal(referenceForms.length,3,'Original three PDF cards unchanged');
for(const [n,file] of [[1,'V_Swaraj_Gramsoft_Right_to_Service_Form_1.pdf'],[2,'V_Swaraj_Gramsoft_Right_to_Service_Form_2.pdf']]){
 const src=readFileSync(new URL(`../../V_Swaraj_Gramsoft_Right_to_Service_Form_${n===1?'1(2)':'2(1)'}.pdf`,import.meta.url));
 const dist=readFileSync(new URL(`../assets/forms/${file}`,import.meta.url));
 assert.equal(createHash('sha256').update(src).digest('hex'),createHash('sha256').update(dist).digest('hex'),'User PDFs preserved exactly');
 assert(referenceFormsPaths.has('/assets/forms/'+file));
 assert(readFileSync(new URL(`../apps/public/assets/forms/${file}`,import.meta.url)).equals(dist),'PDF present in public Vercel app');
}
const html=renderServicesPage(a,[],'mr');
assert(html.includes('V_Swaraj_Gramsoft_Form_2.pdf'),'Original download remains');
assert(html.includes('V_Swaraj_Gramsoft_Right_to_Service_Form_1.pdf'),'Uploaded PDF 1 is linked');
assert(html.includes('V_Swaraj_Gramsoft_Right_to_Service_Form_2.pdf'),'Uploaded PDF 2 is linked');
assert(html.includes('इतर PDF प्रती'),'Extra links remain folded, no duplicate cards');
assert(!readFileSync(new URL('../apps/public/vercel.json',import.meta.url),'utf8').includes('MAJHIGRAM TECH'));
console.log('PASS v4.7.2: four exact reference titles, no fake stats, data isolation, original footer copy, and 2 original PDF uploads');
