import assert from 'node:assert/strict';
import {renderAboutPage} from '../src/about.js';
import {getDemo} from '../src/demo.js';
import {buildShamvadiVillage} from '../src/templates.js';
import {FIXED_DUTIES,FIXED_MISSION_MR,FIXED_VALUES_MR} from '../src/about-reference.js';
import {readFile} from 'node:fs/promises';
globalThis.location={search:''};
const draft=buildShamvadiVillage({slug:'new-village',name_mr:'नवीन गाव',name_en:'New village'});
const village={...draft,id:'00000000-0000-4000-8000-000000000001'};
const html=renderAboutPage(village,[],'mr');
assert.equal(FIXED_DUTIES.length,8);
assert.equal((html.match(/class="sv-a-duty sv-about-section sv-a-duty-reference"/g)||[]).length,8);
for(const line of FIXED_MISSION_MR)assert(html.includes(line),`Mission template must contain exact reference: ${line}`);
for(const line of FIXED_VALUES_MR)assert(html.includes(line),`Values template must contain exact reference: ${line}`);
for(const role of FIXED_DUTIES){
 assert(html.includes(role.title_mr),`missing reference role ${role.title_mr}`);
 for(const line of role.bullets_mr)assert(html.includes(line),`missing unmodified reference duty: ${line}`);
}
assert(!html.includes('5640')&&!html.includes('435453')&&!html.includes('434212'),'new village must never display Shamvadi-specific numbers');
assert(!html.includes('शामवाडी'),'new village must never inherit a reference village name');
const changed={...village,site_settings:{about_mission_mr:'अतिरिक्त ध्येय',about_vision_mr:'अतिरिक्त मूल्य'}};
const extra={id:'c1',kind:'duties',sort_order:1,title_mr:'नवीन पद',title_en:'Additional Role',body_mr:'एक नवीन काम.',body_en:'One additional task.',details:{accent:'#ff8800',icon:'★'}};
const matching={id:'c2',kind:'duties',sort_order:2,title_mr:'सरपंच',title_en:'Sarpanch',body_mr:'अतिरिक्त जबाबदारी.',body_en:'Additional responsibility.',details:{}};
const withExtra=renderAboutPage(changed,[extra,matching],'mr');
assert(withExtra.includes('अतिरिक्त ध्येय') && withExtra.includes('अतिरिक्त मूल्य'));
assert(withExtra.includes('एक नवीन काम.') && withExtra.includes('अतिरिक्त जबाबदारी.'));
assert.equal((withExtra.match(/data-reference-card="sarpanch"/g)||[]).length,1,'existing role additions should not create duplicate fixed cards');
assert.equal((withExtra.match(/sv-a-duty-extra/g)||[]).length,1);
for(const role of FIXED_DUTIES)for(const line of role.bullets_mr)assert(withExtra.includes(line),'extras must not override base copy');
const broken={...changed,site_settings:{...changed.site_settings,about_mission_heading_mr:'HACKED',about_duties_heading_mr:'HACKED'}};
const locked=renderAboutPage(broken,[],'mr');
assert(locked.includes('दृष्टिकोन व ध्येय'));
const original=FIXED_DUTIES.find(x=>x.key==='sarpanch').bullets_mr[0];
assert(locked.includes(original));
const {village:demo,items:demoItems}=getDemo();
const demoHtml=renderAboutPage(demo,demoItems,'mr');
assert.equal((demoHtml.match(/sv-a-duty-reference/g)||[]).length,8);
assert.equal((demoHtml.match(/sv-a-duty-extra/g)||[]).length,0,'demo-only placeholder duty items not duplicated');
const admin=await readFile(new URL('../src/admin.js',import.meta.url),'utf8');
assert(admin.includes('admin-v44-static-reference') && admin.includes('cannot be edited or deleted'));
assert(!admin.includes("['about_mission_heading_mr','Mission heading — Marathi']"),'hardcoded mission title should not remain editable');
const en=renderAboutPage(village,[],'en');
assert(en.includes('Vision and Mission')&&en.includes('Core Values')&&en.includes('Water Supply Employee'));
console.log('PASS V4.4: every new village shows all fixed reference bullets/cards; optional additions cannot replace them; no fake village facts, no double demo cards');
