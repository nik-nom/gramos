import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {getDemo} from '../src/demo.js';
import {homeHeader,homeFooter,homeBottomLogo,renderShamvadiHomepage} from '../src/homepage.js';
import {renderContactPage} from '../src/contact.js';
import {renderNoticesPage} from '../src/notices.js';
import {renderServicesPage} from '../src/services.js';
const {village,items}=getDemo();
globalThis.location={origin:'http://localhost:8000',search:'',pathname:'/demo'};
globalThis.window={GRAMOS_CONFIG:{turnstileSiteKey:''}};
globalThis.document={title:''};
const {renderPublic}=await import('../src/public.js');
const logo='https://cdn.example.org/custom-logo.png';
const v={...village,slug:'shirpur',site_settings:{...village.site_settings,footer_logo_url:logo,footer_social_heading_mr:'समाज माध्यमे',copyright_mr:'Do not print this'}};
const home=renderShamvadiHomepage(v,items,'mr',false);
const contentIndex=home.lastIndexOf('</main>'),brandIndex=home.indexOf('sv-page-logo-band'),footerIndex=home.indexOf('<footer class="sv-footer">');
assert(contentIndex<brandIndex && brandIndex<footerIndex,'Logo belongs between content and footer');
assert(home.includes(logo),'Uploaded logo must appear');
assert(!home.includes('Do not print this')&&home.includes('Copyright © 2026'),'Fixed company copyright must override old admin text');
const footer=homeFooter(v,'mr');
assert.match(footer,/>समाजमाध्यमे<\/a>/);
assert.doesNotMatch(footer,/>Social Media<\/a>|sv-footer-bottom-brand/);
assert.match(footer,/sv-copyright/);
// Demo data contains a sample office address; never replace an empty real address with a fabricated one.
const noDetails={...v,address_mr:'',address_en:'',phone:'',email:'',site_settings:{footer_logo_url:logo}};
assert.match(homeFooter(noDetails,'mr'),/पत्ता, फोन किंवा ईमेल ॲडमिनमधून जोडा/);
const withAddress={...noDetails,address_mr:'वास्तविक कार्यालयाचा पत्ता',phone:'0123',email:'office@example.org',site_settings:{...noDetails.site_settings,office_hours_mr:'10-5'}};
assert.match(homeFooter(withAddress,'mr'),/वास्तविक कार्यालयाचा पत्ता/);
assert.match(homeFooter(withAddress,'mr'),/office@example.org/);
const contact=renderContactPage(noDetails,'mr');
assert.match(contact,/समाजमाध्यमे/);
assert.match(contact,/कार्यालयाचा पत्ता ॲडमिनमधून जोडल्यावर येथे दिसेल/);
assert(!contact.includes('href="https://www.google.com/maps/search'),'Do not invent a map search address');
const header=homeHeader(v,'mr','en');
assert.match(header,/>Home<\/a>/);
assert.match(header,/class="sv-lang-picker"/);
assert.match(header,/data-action="set-nav-language" data-lang="mr"/);
assert.match(header,/data-action="set-nav-language" data-lang="en"/);
assert.match(header,/>English<\/button>/);
assert.match(header,/ग्रामपंचायत/,'English navigation must not force body branding to English');
for(const route of [['demo'],['demo','about'],['demo','services'],['demo','schemes'],['demo','beneficiaries'],['demo','projects'],['demo','notices'],['demo','news'],['demo','news','clean-village-drive'],['demo','gallery'],['demo','contact']]) {
 const page=await renderPublic(route,'en',{admin:false,ids:[]});
 assert(page.indexOf('sv-page-logo-band')>page.indexOf('</main>'),`Logo missing after content: ${route}`);
 assert(page.indexOf('sv-page-logo-band')<page.indexOf('<footer class="sv-footer">'),`Logo not above footer: ${route}`);
 assert(page.includes('sv-copyright'),`Copyright missing: ${route}`);
 assert(page.includes('data-lang="mr"') && page.includes('data-lang="en"'),`Language menu missing: ${route}`);
}
const notices=renderNoticesPage(village,items,'mr');
assert.match(notices,/sv-n-download/);assert.match(notices,/\.pdf/);
assert.match(renderNoticesPage(v,[], 'mr'),/sv-n-empty/);
const forms=renderServicesPage(village,items,'mr');
assert.match(forms,/services-panel-forms/);
const admin=readFileSync(new URL('../src/admin.js',import.meta.url),'utf8');
const data=readFileSync(new URL('../src/data.js',import.meta.url),'utf8');
const css=readFileSync(new URL('../styles.css',import.meta.url),'utf8');
const main=readFileSync(new URL('../src/main.js',import.meta.url),'utf8');
for(const kind of ['notices','service_forms','services'])assert(admin.includes(`kind==='${kind}'`),'PDF admin type missing '+kind);
assert(admin.includes('data-document-input'));
assert(admin.includes('name="external_url"') || admin.includes("field('external_url'"));
assert(admin.includes('Open attached PDF'));
assert(admin.includes('class="admin-lang-picker"'),'Admin also has a language dropdown');
assert(admin.includes('Download files must link directly to a .pdf document'));
const {safePdfURL}=await import('../src/utils.js');
assert.equal(safePdfURL('https://official.example/app.pdf?version=1'),'https://official.example/app.pdf?version=1');
assert.equal(safePdfURL('https://official.example/webpage'),'');
assert.equal(safePdfURL('javascript:alert(1)'),'');
assert(data.includes("storage.from('service-documents').upload(path,file"));
assert(data.includes("getPublicUrl(path)"));
assert(main.includes('documentUpload(e.target)'));
assert(main.includes("action==='set-nav-language'"));
assert(css.includes('.sv-page-logo-band') && css.includes('.sv-lang-picker:not([open])'));
assert.doesNotMatch(homeFooter(v,'mr'),/<a href="javascript:/);
console.log('PASS v3.8 compatibility: page-bottom logo on 11 routes; transliterated social label; editable copyright; nav language menu; document/admin/storage wiring.');
