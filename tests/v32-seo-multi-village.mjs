import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {SEO_PAGES,resolveSEO} from '../src/seo.js';
import {buildShamvadiVillage} from '../src/templates.js';
const file=path=>readFileSync(new URL(path,import.meta.url),'utf8');
const a={...buildShamvadiVillage({slug:'village-a',name_mr:'पहिले गाव',name_en:'Village A'}),status:'published'};
const b={...buildShamvadiVillage({slug:'village-b',name_mr:'दुसरे गाव',name_en:'Village B'}),status:'published'};
a.site_settings={...a.site_settings,seo:{home:{title:'पहिले गाव – अधिकृत संकेतस्थळ',description:'पहिल्या गावाचा स्वतःचा मजकूर.',keywords:'पहिले,सेवा',image_url:'https://example.org/first.webp',noindex:false},services:{title:'पहिली लोकसेवा',description:'या गावाच्या सेवा.',noindex:false}}};
const ma=resolveSEO(a,'home',{origin:'https://example.org'}),mb=resolveSEO(b,'home',{origin:'https://example.org'});
assert.equal(ma.title,'पहिले गाव – अधिकृत संकेतस्थळ');
assert.equal(ma.canonical,'https://example.org/v/village-a');
assert.equal(ma.image,'https://example.org/first.webp');
assert.equal(mb.title,'ग्रामपंचायत दुसरे गाव');
assert.equal(mb.canonical,'https://example.org/v/village-b');
assert.ok(!mb.description.includes('पहिल्या गावाचा'));
assert.equal(resolveSEO(a,'services',{origin:'https://example.org'}).title,'पहिली लोकसेवा');
assert.equal(resolveSEO(a,'notices',{origin:'https://example.org'}).title,'नोटीस बोर्ड | ग्रामपंचायत पहिले गाव');
assert.equal(resolveSEO(a,'home',{preview:true}).robots,'noindex,nofollow');
assert.equal(resolveSEO({...a,status:'draft'},'home').robots,'noindex,nofollow');
assert.equal(resolveSEO({...a,slug:'demo',id:'demo'},'home').robots,'noindex,nofollow');
assert.equal(resolveSEO({...a,site_settings:{seo:{home:{noindex:true}}}},'home').robots,'noindex,nofollow');
assert.equal(SEO_PAGES.length,14); // v3.5 adds indexed beneficiary lists page.
const index=file('../index.html'),main=file('../src/main.js'),admin=file('../src/admin.js'),publicSite=file('../src/public.js');
assert.match(index,/role="status" aria-live="polite">Loading…<\/div>/);
assert.doesNotMatch(index,/class="initial-loading"><img/);
assert.match(main,/initial-loading" role="status" aria-live="polite">Loading…/);
assert.doesNotMatch(main,/class="initial-loading"><img/);
assert.match(admin,/function seoEditor/);assert.match(admin,/id="seoSettingsForm"/);
assert.match(admin,/section==='seo'\?seoEditor/);
assert(admin.includes("['home',tr(lang,'मुख्यपृष्ठ','Home page'),'home']"),'Separate homepage editor must be listed'); assert(admin.includes("section==='seo'?seoEditor"),'SEO editor must remain available');
assert.match(admin,/site_settings=\{\.\.\.current,seo:\{\.\.\.previous,\[page\]:value\}\}/);
assert.match(admin,/api\.from\('villages'\)\.update\(\{site_settings\}\)\.eq\('id',form\.dataset\.id\)/);
assert.match(publicSite,/applyPublicMetadata\(v,section,\{preview,article\}\)/);
console.log('PASS v3.2: exact village-aware Marathi titles, page-specific metadata, scoped saves, multi-site defaults, noindex and logo-free loading');
